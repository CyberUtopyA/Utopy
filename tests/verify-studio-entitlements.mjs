import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { resolve } from 'node:path';
import { createServer } from 'vite';
import { createIdentity, createEnvelope, signEnvelope } from 'utopy';
const studio = process.env.UTOPY_STUDIO_REPO || resolve('../../LyV/lyv');
const php = spawnSync(process.env.PHP_BINARY || 'php', [resolve(studio, 'tests/studio-projection.php'), '--json'], { encoding:'utf8' });
if(php.status !== 0) throw Error(php.stderr || 'PHP projection unavailable');
const dv = JSON.parse(php.stdout);
const vite = await createServer({server:{middlewareMode:true},appType:'custom',logLevel:'silent'});
try {
  const trust=await vite.ssrLoadModule('/src/utopy/runtimeTrust.ts');
  const projection=await vite.ssrLoadModule('/src/utopy/runtimeProjection.security.ts');
  const grants=await vite.ssrLoadModule('/src/utopy/studioEntitlements.ts');
  const ingest=await vite.ssrLoadModule('/src/mt/mt.ingest.ts');
  const store=await vite.ssrLoadModule('/src/mt/mt.liveStore.ts');
  const identity=await createIdentity({actorId:'studio-test',nodeId:dv.meta.authority});
  const sign=async(draft)=>signEnvelope(await createEnvelope({sourceActorId:identity.actorId,sourceNodeId:identity.nodeId,authority:identity.nodeId,...draft}),identity);
  const manifest=await sign({id:'studio-test-manifest',kind:'utopy.node.manifest',scopes:['public'],expiresAt:new Date(Date.now()+60000).toISOString(),payload:{nodeId:identity.nodeId,issuedAt:new Date().toISOString(),capabilities:[]}});
  trust.resetRuntimeTrustForTests();
  assert.equal((await trust.verifyRuntimeEnvelope(manifest)).verified,true);
  const signed=await sign({id:dv.id,kind:dv.kind,revision:dv.meta.revision,scopes:['participants'],targetNodeId:dv.attrs.nodeId,participants:dv.attrs.participants,payload:{dv}});
  assert.equal((await trust.verifyRuntimeEnvelope(signed)).verified,true);
  const result=projection.projectVerifiedRuntimeEnvelope(signed);
  assert.equal(result.accepted,true);
  assert.equal(grants.activeEntitlementDVs([result.dv],'actor-test').length,1);
  assert.equal(grants.activeEntitlementDVs([result.dv],'stranger').length,0);
  assert.equal(grants.activeEntitlementDVs([result.dv],'delegate',['node-test']).length,1);
  assert.equal(grants.activeEntitlementDVs([result.dv],'actor-test',[],Date.now()+7200000).length,0);
  const cancelled={...result.dv,attrs:{...result.dv.attrs,status:'cancelled',revision:5},meta:{...result.dv.meta,runtimeRevision:5}};
  assert.equal(grants.activeEntitlementDVs([cancelled,result.dv],'actor-test').length,0);
  const forged=structuredClone(signed);forged.payload.dv.attrs.nodeId='wrong';
  assert.equal(projection.projectVerifiedRuntimeEnvelope(forged).accepted,false);
  ingest.ingestFrame({dv:signed});
  for(let i=0;i<50&&!store.mtLiveSnapshot().some((item)=>item.id===dv.id);i++)await new Promise((r)=>setTimeout(r,20));
  const received=store.mtLiveSnapshot().find((item)=>item.id===dv.id);
  assert.equal(received?.meta?.runtimeVerified,true);
  assert.equal(received.attrs.nodeId,'node-test');
  assert.equal(received.attrs.actorId,'actor-test');
  assert.equal(received.attrs.panel.automations[0].enabled,true);
  console.log('OK: PHP Pass DV → Runtime signature → Market verification → shared store → personalized modules/automations; identity isolation and expiry/revocation.');
} finally {await vite.close();}
