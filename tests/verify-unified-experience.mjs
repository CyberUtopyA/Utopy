import assert from "node:assert/strict";
import fs from "node:fs";
import { createServer, transformWithEsbuild } from "vite";
const server = await createServer({ server: { middlewareMode: true }, appType: "custom", logLevel: "silent" });
try {
  const cashier = await server.ssrLoadModule("/src/pay/livingCashier.ts");
  for (const amount of [0, -1, NaN, Infinity, Number.MAX_SAFE_INTEGER + 1]) assert.throws(() => cashier.validateChargeDraft(amount, "PYG"));
  assert.throws(() => cashier.validateChargeDraft(1.5, "PYG"));
  assert.throws(() => cashier.validateChargeDraft(1.234, "USD"));
  assert.throws(() => cashier.validateChargeDraft(10, "EUR"));
  assert.doesNotThrow(() => cashier.validateChargeDraft(5000, "PYG"));
  assert.doesNotThrow(() => cashier.validateChargeDraft(12.5, "BRL"));
  await assert.rejects(() => cashier.createLivingCharge({ allLive: [], amount: 0, currency: "PYG" }));
  const ux = await server.ssrLoadModule("/src/utopy/livingNodeUX.ts");
  assert.equal(ux.humanCapability({ label: "voz", verbs: [], resources: [] }), "");
  assert.equal(ux.humanCapability({ label: "resultado vivo", verbs: [], resources: [] }), "");
  const signal = { id: "signal:one", kind: "live.signal", attrs: { actorId: "actor:test", title: "Necesito reparar una mesa" }, meta: { version: 1, updatedAt: "2026-10-15T12:00:00Z" } };
  const groups = ux.groupLivingActivity([signal, signal, { ...signal, meta: { ...signal.meta, version: 2 } }], []);
  assert.equal(groups.length, 1); assert.equal(groups[0].count, 1);
  assert.equal(ux.groupLivingActivity([{ ...signal, attrs: { title: "voz" } }], []).length, 0);
  const profile = fs.readFileSync("src/social/LiveNetworkPanel.tsx", "utf8");
  for (const section of ["Perfil público", "Currículum", "Disponibilidad", "Datos privados"]) assert.ok(profile.includes(section));
  assert.match(profile, /if \(profileSection !== "private"\) \{\s*await publishLiveNetworkDV/);
  assert.match(profile, /if \(profileSection === "private"\) \{\s*const saved = await savePrivateLivingIdentity/);
  assert.doesNotMatch(profile, /summary[^>]*>Caja Viva y formas de cobro/);
  const panel = fs.readFileSync("src/pay/LivingCashierPanel.tsx", "utf8");
  assert.match(panel, /if \(running.current\) return/);
  assert.match(panel, /Revisar solicitud/);
  assert.match(panel, /Generar solicitud/);
  assert.match(panel, /Todavía no confirma un pago/);
  const domain = fs.readFileSync("src/pay/livingCashier.ts", "utf8");
  assert.match(domain, /input.requestId \|\|/); assert.match(domain, /verifyAuthorizedDV\(existing/);
  assert.match(domain, /verifyAuthorizedDV\(capability/);
  assert.match(domain, /status: "open"/); assert.doesNotMatch(domain, /status: "paid"|status: "settled"/);
  const market = fs.readFileSync("src/pages/mercado.tsx", "utf8");
  assert.match(market, /if \(next === "producir"\) \{ setTab\("crear"\)/);
  assert.match(market, /requestedTab === "producir" \? "mis_pedidos"/);
  assert.match(market, /surfaceTab === "mis_pedidos" && !activityOperational/);
  const resume = fs.readFileSync("src/components/LivingResume.tsx", "utf8");
  assert.doesNotMatch(resume, /<video|<iframe|type="file"/);
  for (const file of ["src/social/LiveNetworkPanel.tsx", "src/pay/LivingCashierPanel.tsx", "src/pay/livingCashier.ts", "src/components/LivingProfileQuickView.tsx", "src/components/LivingResume.tsx", "src/components/FalconShell.tsx", "src/pages/mercado.tsx", "src/pages/circularcenter.tsx", "src/utopy/livingNodeUX.ts"]) await transformWithEsbuild(fs.readFileSync(file, "utf8"), file, { loader: "tsx" });
  console.log("✓ Convergencia UX: publicación pública/privada separada, validación de importes sin transacciones, deduplicación de proyecciones, creación única, legacy Actividad, revisión de cobro, enlaces y sintaxis.");
} finally { await server.close(); }
