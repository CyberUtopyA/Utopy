import assert from "node:assert/strict";
import fs from "node:fs";
import { transformWithEsbuild } from "vite";
const asset = "public/media/skylines/renta-001/pieza-5/recorrido.mp4";
assert.equal(fs.statSync(asset).size, 4339081);
assert.equal(fs.readFileSync(asset).toString("ascii", 4, 8), "ftyp");
const source = fs.readFileSync("src/mt/skylines.rentals.ts", "utf8");
const migration = source.slice(source.indexOf("async function migrateKm2RoomFiveVideo"), source.indexOf("async function migrateKm2RoomFivePhoto"));
assert.match(migration, /attrs: \{ \.\.\.existing.attrs, video \}/);
assert.match(migration, /roomFiveVideoMigration === migration/);
assert.doesNotMatch(migration, /price:|available:|photos:|state:/);
const photoMigration = source.slice(source.indexOf("async function migrateKm2RoomFivePhoto"), source.indexOf("let readiness:"));
assert.match(photoMigration, /roomFivePhotoMigration === migration/);
assert.match(photoMigration, /attrs: \{ \.\.\.existing.attrs, image, photos \}/);
assert.doesNotMatch(photoMigration, /price:|available:|state:|video:/);
assert.equal(fs.statSync("public/media/skylines/renta-001/pieza-5/habitacion-5.png").size, 311170);
assert.equal(fs.readFileSync("public/media/skylines/renta-001/pieza-5/habitacion-5.png").toString("ascii", 1, 4), "PNG");
const page = fs.readFileSync("src/pages/renta.jsx", "utf8");
assert.match(page, /controls playsInline preload="none"/);
assert.doesNotMatch(page, /<video[^>]*autoPlay/);
await transformWithEsbuild(page, "src/pages/renta.jsx", { loader: "jsx" });
await transformWithEsbuild(source, "src/mt/skylines.rentals.ts", { loader: "ts" });
console.log("✓ Pieza 5: MP4 real, actualización de medios idempotente sin cambiar precios/estado, reproducción manual y sintaxis.");
